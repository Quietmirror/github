"""Archive actual candidate geometry as deltas against preserved R3.2."""
from pathlib import Path
import zipfile,json,hashlib,sys
ROOT=Path(__file__).resolve().parents[2];OUT=ROOT/'releases/Quietmirror-L2-Research/history';OUT.mkdir(parents=True,exist_ok=True)
def main():
 from restore_history import prepare
 prepare()
 index=[];baseline=ROOT/'exports/rebuild_r3_2'
 for folder in sorted((ROOT/'exports/l2_revision').iterdir()):
  if not folder.is_dir() or folder.name in ['L2_H_EST','L2_D_EST','L2_BOTH_EST','partitions','partitions_v2']:continue
  files=[p for p in folder.rglob('*') if p.is_file() and p.suffix.lower()=='.step' and ('assembly' in p.parts or folder.name=='failed_construction')];manifest=[];target=OUT/(folder.name+'_CAD_DELTA.zip')
  with zipfile.ZipFile(target,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
   for p in files:
    rel=p.relative_to(folder).as_posix();b=baseline/rel;data=p.read_bytes();same=b.exists() and data==b.read_bytes()
    manifest.append(dict(path=rel,source='R3.2 preserved baseline' if same else 'included',bytes=len(data)))
    if not same:z.writestr(rel,data)
   z.writestr('RESTORE_MANIFEST.json',json.dumps(dict(version=folder.name,baseline_commit='f1b1090931d717117287ea2b79c2e14ddc234937',baseline_directory='exports/rebuild_r3_2',files=manifest),indent=2))
   z.writestr('README.txt','Research CAD history; failed candidates are NOT printable releases. Contains original individual assembly STEP geometry; unchanged R3.2 parts referenced in manifest. STL/print transforms are regenerated by cad/l2_revision scripts and per-version metadata; raw meshes remain local. Selected common/H/D kits ship complete STL and STEP separately. Final review is in reports/l2_revision.\n')
  with zipfile.ZipFile(target) as z:assert z.testzip() is None
  index.append(dict(version=folder.name,archive=target.relative_to(ROOT).as_posix(),bytes=target.stat().st_size,files=len(files),included=sum(q['source']=='included' for q in manifest)))
  print(folder.name,target.stat().st_size,flush=True)
 (OUT/'INDEX.json').write_text(json.dumps(index,indent=2)+'\n')
if __name__=='__main__':main()
